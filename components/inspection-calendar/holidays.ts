export const holidayOf = (ds: string): Holiday | null => HOLIDAYS[ds] || null;

/** 그 달의 공휴일·국경일 목록 (사이드 패널용) */
export const holidaysInMonth = (y: number, m: number) => {
  const pre = `${y}-${String(m).padStart(2, '0')}-`;
  return Object.entries(HOLIDAYS)
    .filter(([d]) => d.startsWith(pre))
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([date, h]) => ({ date, ...h }));
};
